#!/bin/sh
# Compile the SDL_GPU shaders (ui.hlsl, nanovg.hlsl) to SPIR-V (Vulkan) and DXIL
# (Direct3D 12) with DXC, and to MSL (Metal) from the SPIR-V with SPIRV-Cross; write
# each into <name>_shaders.h as <name>_{vs,ps}_{spv,dxil,msl}.
#   DXC=path/to/dxc SPIRV_CROSS=path/to/spirv-cross shaders/build.sh
set -eu
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DXC=${DXC:-dxc}
SPVC=${SPIRV_CROSS:-spirv-cross}
PHP=${PHP:-$(command -v php84 || command -v php)}
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' 0
for src in "$DIR"/*.hlsl; do
    name=$(basename "$src" .hlsl)
    for stage in vs ps; do
        entry=$([ $stage = vs ] && echo VSMain || echo PSMain)
        "$DXC" -T ${stage}_6_0 -E $entry -spirv -fspv-target-env=vulkan1.0 -Fo "$OUT/$stage.spv" "$src"
        "$DXC" -T ${stage}_6_0 -E $entry -Fo "$OUT/$stage.dxil" "$src"
        "$SPVC" --msl --msl-version 20100 --msl-decoration-binding --rename-entry-point $entry main0 $([ $stage = vs ] && echo vert || echo frag) "$OUT/$stage.spv" --output "$OUT/$stage.msl"
    done
    "$PHP" -r '
    [, $dir, $name, $file] = $argv;
    $guard = "PHPSDL_" . strtoupper($name) . "_SHADERS_H";
    $out = "/* Generated by shaders/build.sh from $name.hlsl. */\n#ifndef $guard\n#define $guard\n\n";
    foreach (["vs", "ps"] as $stage) foreach (["spv", "dxil", "msl"] as $format) {
        $bytes = file_get_contents("$dir/$stage.$format");
        if ($format === "msl") $bytes .= "\0";
        $out .= "static const unsigned char {$name}_{$stage}_{$format}[] = {" . implode(",", array_map("ord", str_split($bytes))) . "};\n";
    }
    file_put_contents($file, $out . "\n#endif\n");
    ' "$OUT" "$name" "$DIR/${name}_shaders.h"
    ls -la "$DIR/${name}_shaders.h"
done
