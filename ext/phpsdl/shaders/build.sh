#!/bin/sh
# Compile ui.hlsl for SDL_GPU: SPIR-V (Vulkan) and DXIL (Direct3D 12) with DXC, MSL
# (Metal) from the SPIR-V with SPIRV-Cross; write them into ui_shaders.h.
#   DXC=path/to/dxc SPIRV_CROSS=path/to/spirv-cross shaders/build.sh
set -eu
DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DXC=${DXC:-dxc}
SPVC=${SPIRV_CROSS:-spirv-cross}
PHP=${PHP:-$(command -v php84 || command -v php)}
OUT=$(mktemp -d)
trap 'rm -rf "$OUT"' 0
for stage in vs ps; do
    entry=$([ $stage = vs ] && echo VSMain || echo PSMain)
    "$DXC" -T ${stage}_6_0 -E $entry -spirv -fspv-target-env=vulkan1.0 -Fo "$OUT/$stage.spv" "$DIR/ui.hlsl"
    "$DXC" -T ${stage}_6_0 -E $entry -Fo "$OUT/$stage.dxil" "$DIR/ui.hlsl"
    "$SPVC" --msl --msl-version 20100 --msl-decoration-binding --rename-entry-point $entry main0 $([ $stage = vs ] && echo vert || echo frag) "$OUT/$stage.spv" --output "$OUT/$stage.msl"
done
"$PHP" -r '
$dir = $argv[1];
$out = "/* Generated by shaders/build.sh from ui.hlsl. */\n#ifndef PHPSDL_UI_SHADERS_H\n#define PHPSDL_UI_SHADERS_H\n\n";
foreach (["vs", "ps"] as $stage) foreach (["spv", "dxil", "msl"] as $format) {
    $bytes = file_get_contents("$dir/$stage.$format");
    if ($format === "msl") $bytes .= "\0";
    $out .= "static const unsigned char ui_{$stage}_{$format}[] = {" . implode(",", array_map("ord", str_split($bytes))) . "};\n";
}
file_put_contents($argv[2], $out . "\n#endif\n");
' "$OUT" "$DIR/ui_shaders.h"
ls -la "$DIR/ui_shaders.h"
