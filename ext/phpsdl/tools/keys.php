<?php
// Write phpsdl_keys.h: GLFW_KEY_*, GLFW_MOD_*, GLFW_MOUSE_BUTTON_* and action constants
// with GLFW's values, so apps and the toolkit keep using them on phpsdl.
[$header, $out] = [$argv[1], $argv[2]];
preg_match_all('/^#define\s+(GLFW_(?:KEY|MOD|MOUSE_BUTTON)_[A-Z0-9_]+|GLFW_(?:PRESS|RELEASE|REPEAT))\s+(\S+)/m', file_get_contents($header), $m, PREG_SET_ORDER);
$values = [];
foreach ($m as [, $name, $value]) $values[$name] = $value;
$resolve = function ($v) use (&$resolve, $values) { return is_numeric($v) ? (int) $v : (str_starts_with($v, '0x') ? hexdec($v) : $resolve($values[$v])); };
$lines = ["/* Generated by tools/keys.php from GLFW 3.4's glfw3.h: GLFW's key, modifier and button numbering. */",
    '#ifndef PHPSDL_KEYS_H', '#define PHPSDL_KEYS_H', '', 'static const struct { const char *name; int value; } phpsdl_glfw_constants[] = {'];
foreach ($values as $name => $v) $lines[] = sprintf('    {"%s", %d},', $name, $resolve($v));
$lines[] = '    {NULL, 0}';
$lines[] = '};';
$lines[] = '';
$lines[] = '#endif';
file_put_contents($out, implode("\n", $lines) . "\n");
echo count($values), " constants\n";
